const dicts = { en, zh }
export type TKey = keyof typeof en

const DAY_NAMES_I18N: Record<Lang, string[]> = {
  en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
  zh: ['星期日', '星期一', '星期二', '星期三', '星期四', '星期五', '星期六'],
}

const DAY_SHORT_I18N: Record<Lang, string[]> = {
  en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
  zh: ['周日', '周一', '周二', '周三', '周四', '周五', '周六'],
}

const MONTH_SHORT_I18N: Record<Lang, string[]> = {
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  zh: ['1月', '2月', '3月', '4月', '5月', '6月', '7月', '8月', '9月', '10月', '11月', '12月'],
}

// Module-level current language so non-component helpers (dates, weather) translate too.
// The provider re-renders the whole tree on change, so every t() call re-evaluates.
let current: Lang = (localStorage.getItem(LANG_KEY) as Lang) || 'en'

export function getLang(): Lang {
  return current
}

/** Translate a key, with optional {placeholder} substitutions */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[current][key] ?? en[key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

export const dayName = (i: number) => DAY_NAMES_I18N[current][i]
export const dayShort = (i: number) => DAY_SHORT_I18N[current][i]
export const monthShort = (i: number) => MONTH_SHORT_I18N[current][i]

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: current,
  setLang: () => {},
})

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current)
  const setLang = (l: Lang) => {
    current = l
    localStorage.setItem(LANG_KEY, l)
    setLangState(l)
  }
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}
